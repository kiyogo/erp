export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageType>(() => {
    try {
      const saved = localStorage.getItem('kiyovn_language') || localStorage.getItem('minepanel_lang');
      return (saved as LanguageType) || 'vi';
    } catch {
      return 'vi';
    }
  });

  const setLanguage = (lang: LanguageType) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('minepanel_lang', lang);
      localStorage.setItem('kiyovn_language', lang);
      window.dispatchEvent(new Event('kiyovn-settings-updated'));
    } catch {}
  };

  useEffect(() => {
    const handleSync = () => {
      try {
        const saved = localStorage.getItem('kiyovn_language') || localStorage.getItem('minepanel_lang');
        if (saved && (saved === 'vi' || saved === 'en' || saved === 'ja' || saved === 'zh')) {
          setLanguageState(saved);
        }
      } catch {}
    };
    window.addEventListener('storage', handleSync);
    window.addEventListener('kiyovn-settings-updated', handleSync);
    return () => {
      window.removeEventListener('storage', handleSync);
      window.removeEventListener('kiyovn-settings-updated', handleSync);
    };
  }, []);

  const t = (key: string) => {
    const keys = key.split('.');
    let val: any = translations[language];
    const extraVal = extraTranslations[language];
    
    // Check extra translations first
    let extraTemp = extraVal;
    let foundInExtra = true;
    for (const k of keys) {
      if (extraTemp && extraTemp[k] !== undefined) {
        extraTemp = extraTemp[k];
      } else {
        foundInExtra = false;
        break;
      }
    }
    if (foundInExtra) return extraTemp;

    for (const k of keys) {
      if (val && val[k] !== undefined) {
        val = val[k];
      } else {
        return key;
      }
    }
    return val;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
