import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(path.join(root,'legacy/web/package.json'));
const ts=require('typescript');
export function generate(){
  const source=fs.readFileSync(path.join(root,'legacy/web/src/data/menuData.tsx'),'utf8');
  const tree=ts.createSourceFile('menuData.tsx',source,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
  const ids=[];
  const walk=node=>{
    if(ts.isObjectLiteralExpression(node)){
      const id=node.properties.find(p=>ts.isPropertyAssignment(p)&&p.name.getText(tree)==='id');
      if(id&&ts.isStringLiteral(id.initializer)&&!ids.includes(id.initializer.text))ids.push(id.initializer.text);
    }
    ts.forEachChild(node,walk);
  };walk(tree);
  return `//! Generated by tools/generate_navigation_order.mjs; presentation order only.\n//! Legacy menu SHA-256: ${crypto.createHash('sha256').update(source).digest('hex')}\nuse crate::models::NavNode;\n\npub fn rank(id: &str) -> usize {\n    match id {\n${ids.map((id,i)=>`        ${JSON.stringify(id)} => ${i},`).join('\n')}\n        _ => usize::MAX,\n    }\n}\n\n/// App-only features remain reachable, appended in their existing stable order.\npub fn ordered(nodes: &[NavNode]) -> Vec<&NavNode> {\n    let mut nodes=nodes.iter().collect::<Vec<_>>();\n    nodes.sort_by_key(|node|rank(node.item.id));\n    nodes\n}\n`;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const file=path.join(root,'ui/src/navigation_order.rs'),source=generate();
  if(process.argv.includes('--check')){
    if(fs.readFileSync(file,'utf8').replaceAll('\r\n','\n')!==source)throw new Error('Generated navigation order is stale');
    console.log('Navigation order matches legacy source.');
  }else if(process.argv.includes('--print'))process.stdout.write(source);
  else throw new Error('Use --print to prepare a patch or --check to verify the generated file');
}
